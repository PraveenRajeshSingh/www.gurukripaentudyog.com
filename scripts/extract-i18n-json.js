/**
 * Phase 1 i18n tooling
 *
 * Modes:
 *  1) If src/js/i18n.js still embeds `const TRANSLATIONS = …`, extract → /i18n/*.json + i18n-data.js
 *  2) Otherwise rebuild i18n-data.js from /i18n/en.json + hi.json (source of truth)
 *
 * Usage: node scripts/extract-i18n-json.js
 */
'use strict';
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const i18nDir = path.join(root, 'i18n');
const srcPath = path.join(root, 'src/js/i18n.js');

function writeBundle(en, hi) {
  fs.mkdirSync(i18nDir, { recursive: true });
  fs.writeFileSync(path.join(i18nDir, 'en.json'), JSON.stringify(en, null, 2) + '\n', 'utf8');
  fs.writeFileSync(path.join(i18nDir, 'hi.json'), JSON.stringify(hi, null, 2) + '\n', 'utf8');
  const bundle = `/* AUTO-GENERATED by scripts/extract-i18n-json.js — do not edit by hand.
   Source of truth: /i18n/en.json and /i18n/hi.json
   Sync bundle so first paint needs no network fetch. */
window.__GBI_I18N__ = ${JSON.stringify({ en, hi })};
`;
  fs.writeFileSync(path.join(root, 'src/js/i18n-data.js'), bundle, 'utf8');
}

function parity(en, hi) {
  const enKeys = Object.keys(en);
  const hiKeys = Object.keys(hi);
  const onlyEn = enKeys.filter((k) => !(k in hi));
  const onlyHi = hiKeys.filter((k) => !(k in en));
  return { en: enKeys.length, hi: hiKeys.length, onlyEn, onlyHi };
}

let en;
let hi;
let mode = 'json';

const src = fs.existsSync(srcPath) ? fs.readFileSync(srcPath, 'utf8') : '';
const start = src.indexOf('const TRANSLATIONS = ');
if (start >= 0) {
  mode = 'extract-from-i18n-js';
  let i = src.indexOf('{', start);
  let depth = 0;
  let end = -1;
  for (; i < src.length; i++) {
    const ch = src[i];
    if (ch === '{') depth++;
    else if (ch === '}') {
      depth--;
      if (depth === 0) {
        end = i + 1;
        break;
      }
    }
  }
  if (end < 0) throw new Error('Could not parse TRANSLATIONS object');
  const objSrc = src.slice(src.indexOf('{', start), end);
  const TRANSLATIONS = new Function('return (' + objSrc + ')')();
  en = TRANSLATIONS.en || {};
  hi = TRANSLATIONS.hi || {};
} else {
  en = JSON.parse(fs.readFileSync(path.join(i18nDir, 'en.json'), 'utf8'));
  hi = JSON.parse(fs.readFileSync(path.join(i18nDir, 'hi.json'), 'utf8'));
}

if (!en['products.filters']) en['products.filters'] = 'Filters';
if (!hi['products.filters']) hi['products.filters'] = 'फ़िल्टर';

writeBundle(en, hi);
const report = Object.assign({ mode, out: ['i18n/en.json', 'i18n/hi.json', 'src/js/i18n-data.js'] }, parity(en, hi));
console.log(JSON.stringify(report, null, 2));
if (report.onlyEn.length || report.onlyHi.length) process.exitCode = 1;
